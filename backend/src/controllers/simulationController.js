import { simulatorInstance } from '../services/simulatorEngine.js';
import { logAuditEvent } from '../middleware/auditLogger.js';

export const getSimulationStatus = async (req, res) => {
  res.status(200).json({
    success: true,
    isRunning: simulatorInstance.isRunning,
    intervalMs: simulatorInstance.intervalMs,
    forcedConditionsCount: simulatorInstance.forcedConditions.size,
    isSimulated: true,
    disclaimer: 'All metrics and fault triggers are generated by the simulation engine and have no hardware connection.',
  });
};

export const startSimulation = async (req, res, next) => {
  try {
    await simulatorInstance.start();
    await logAuditEvent({
      actor: req.user,
      action: 'SIMULATION_STARTED',
      targetType: 'Simulator',
    });
    res.status(200).json({ success: true, message: 'Simulation engine started' });
  } catch (error) {
    next(error);
  }
};

