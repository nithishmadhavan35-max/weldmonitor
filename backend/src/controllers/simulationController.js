export const triggerFault = async (req, res, next) => {
  try {
    const { id } = req.params;
    const { code, message } = req.body;
    const machine = await simulatorInstance.triggerMachineFault(id.toUpperCase(), { code, message });

    await logAuditEvent({
      actor: req.user,
      action: 'SIMULATION_TRIGGER_FAULT',
      targetType: 'Machine',
      targetId: id.toUpperCase(),
      metadata: { code, message },
    });

    res.status(200).json({ success: true, message: `Fault triggered on ${id.toUpperCase()}`, machine });
  } catch (error) {
    next(error);
  }
};

